"""
Turning two numbers into one, and one number into something a person can read.
— Milestone 4 & 5 implementation
"""

import config


def combine_signals(model_score: float, style_score: float) -> float:
    """
    Combine two 0–1 signals into one 0–1 score.

    Both inputs point the same way: higher means more likely AI.
    Uses a weighted blend of model and style signals, incorporating a 
    disagreement mitigation factor to prevent false balancing when signals split.
    """
    # Base weighted combination using config weights
    base_score = (
        config.WEIGHT_MODEL_SIGNAL * model_score
        + config.WEIGHT_STYLE_SIGNAL * style_score
    )

    # Disagreement penalty/mitigation logic:
    # If one signal is extremely high and the other is extremely low (split),
    # lean slightly toward the more conservative human side to reduce false positives.
    disagreement = abs(model_score - style_score)
    if disagreement > 0.5:
        base_score = max(0.0, base_score - (disagreement * 0.15))

    return round(max(0.0, min(1.0, base_score)), 4)


def score_to_label(score: float) -> tuple[str, str]:
    """
    Turn a score into a guess and the text a reader actually sees.
    Written for someone who has never heard the word "threshold".
    """
    if score >= config.AI_THRESHOLD:
        return "ai", "Our analysis indicates this text was very likely generated by an artificial intelligence system."
    if score <= config.HUMAN_THRESHOLD:
        return "human", "We think this was probably written by a person."
    return "unsure", "We could not determine with certainty whether this text was written by a person or an AI."


def label_ranges() -> list[tuple[str, str]]:
    """
    The score range each label covers. Your README needs these beside the
    label text — given to you so the numbers can't drift apart from config.py.
    """
    return [
        ("high-confidence human", f"0.00 – {config.HUMAN_THRESHOLD:.2f}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:.2f} – {config.AI_THRESHOLD:.2f}"),
        ("high-confidence AI", f"{config.AI_THRESHOLD:.2f} – 1.00"),
    ]
